#[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]
pub(crate) struct CompactionDiagnostics {
    pub(crate) old_generation_bytes: u64,
    pub(crate) new_generation_bytes: u64,
    pub(crate) mark_database_bytes: u64,
    pub(crate) candidate_journal_temp_peak_bytes: u64,
    pub(crate) verification_scratch_peak_bytes: u64,
    pub(crate) selector_temporary_bytes: u64,
    pub(crate) total_peak_bytes: u64,
}

impl From<CompactionStorageObservation> for CompactionDiagnostics {
    fn from(value: CompactionStorageObservation) -> Self {
        Self {
            old_generation_bytes: value.old_generation_bytes,
            new_generation_bytes: value.new_generation_bytes,
            mark_database_bytes: value.mark_database_bytes,
            candidate_journal_temp_peak_bytes: value.candidate_journal_temp_peak_bytes,
            verification_scratch_peak_bytes: value.verification_scratch_peak_bytes,
            selector_temporary_bytes: value.selector_temporary_bytes,
            total_peak_bytes: value.total_peak_bytes,
        }
    }
}

