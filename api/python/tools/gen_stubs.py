"""Writes the type stubs that depend on the call table.

    python api/python/tools/gen_stubs.py           # rewrite the stubs
    python api/python/tools/gen_stubs.py --check   # exit 1 when they differ

The table comes from the built native module (`layerfs._native.table()`),
so build the module first (see api/python/README.md). Written:
`src/layerfs/_client.pyi`, `aio.pyi` and `__init__.pyi`. `_values.pyi` and
`_errors.pyi` are written by hand. The table has argument kinds and no
result schema, so every result is the loose `Result`.
"""

import json
import sys
from pathlib import Path

PACKAGE = Path(__file__).resolve().parent.parent / "src" / "layerfs"
HEADER = "# Generated by api/python/tools/gen_stubs.py from the call table; do not edit.\n"
LINE = 120
OPEN_SCOPE = "Scope | Mapping[str, str | None] | None"
HOME = "str | PathLike[str] | None"

#: A table kind as the annotation of its argument.
ANNOTATION = {
    "name": "str",
    "project": "str",
    "text": "str",
    "int": "int",
    "bool": "bool",
    "size": "Size",
    "content": "Content",
    "json": "JSON",
    "image": "str",
}
#: The functions an option may be, by name.
FUNCTIONS = {
    "on_progress": "Callable[[Progress], object]",
    "stdout": "Callable[[Output], object]",
    "stderr": "Callable[[Output], object]",
}


def table():
    sys.path.insert(0, str(PACKAGE.parent))
    from layerfs import _native

    return json.loads(_native.table())


def annotation(arg):
    if arg["kind"] == "function":
        return FUNCTIONS[arg["name"]]
    return ANNOTATION[arg["kind"]]


def method(spec, asynchronous):
    """One call as a stub method: positionals as they are, options keyword-only."""
    params, seen_optional = ["self"], False
    for arg in spec["args"]:
        assert arg["optional"] or not seen_optional, f"{spec['family']}.{spec['call']}: required after optional"
        seen_optional = seen_optional or arg["optional"]
        params.append(f"{arg['name']}: {annotation(arg)}" + (" | None = None" if arg["optional"] else ""))
    params.append("*")
    for opt in spec["options"]:
        default = " = ..." if opt["kind"] == "function" else " | None = None"
        params.append(f"{opt['name']}: {annotation(opt)}{default}")
    # every call takes the tag of its call log line (#659)
    params.append("log_tag: str | None = None")
    keyword = "async def" if asynchronous else "def"
    head = f"    {keyword} {spec['call']}({', '.join(params)}) -> Result:"
    if len(head) > LINE:
        inner = "".join(f"        {param},\n" for param in params)
        head = f"    {keyword} {spec['call']}(\n{inner}    ) -> Result:"
    text = spec["help"]
    assert '"""' not in text and not text.endswith('"'), text
    return f'{head}\n        """{text}"""\n'


def family_names(entries):
    return list(dict.fromkeys(spec["family"] for spec in entries))


def classes(entries, prefix):
    """One class per family, in help order."""
    out = []
    for family in family_names(entries):
        out.append(f"class {prefix}{family.capitalize()}Family:\n")
        out += [method(spec, bool(prefix)) for spec in entries if spec["family"] == family]
        out.append("\n")
    return "".join(out)


def client(entries, prefix):
    fields = "".join(f"    {name}: {prefix}{name.capitalize()}Family\n" for name in family_names(entries))
    # the async client wraps a sync one and does not expose its home or scope
    plain = "" if prefix else f"    home: str | None\n    scope: {OPEN_SCOPE}\n"
    return (
        f"class {prefix}Client:\n"
        f"{plain}"
        f"{fields}"
        f"    def __init__(self, home: {HOME} = None, scope: {OPEN_SCOPE} = None) -> None: ...\n"
        f"\n"
        f"def client(home: {HOME} = None, scope: {OPEN_SCOPE} = None) -> {prefix}Client: ...\n"
    )


def attributes(entries, prefix):
    """The families of the module's default client."""
    return "".join(f"{name}: {prefix}{name.capitalize()}Family\n" for name in family_names(entries))


def render(entries):
    """Every generated stub as `{file name: text}`."""
    names = family_names(entries)
    imports = (
        "from collections.abc import Callable, Mapping\n"
        "from os import PathLike\n"
        "\n"
        "from ._values import JSON, Content, Output, Progress, Result, Scope, Size\n"
    )
    sync = (
        f"{HEADER}\n{imports}\n"
        "TABLE: list[dict[str, object]]\n"
        "FAMILIES: list[str]\n"
        "\n"
        f"{classes(entries, '')}{client(entries, '')}"
    )
    asynchronous = (
        f"{HEADER}\n{imports}from ._errors import LayerFSError as LayerFSError\n\n"
        f"{classes(entries, 'Async')}{client(entries, 'Async')}\n"
        f"{attributes(entries, 'Async')}\n"
        f"__all__ = {['AsyncClient', 'LayerFSError', 'client'] + names!r}\n"
    )
    package = (
        f"{HEADER}\n"
        "from os import PathLike\n"
        "\n"
        "from ._client import (\n"
        "    FAMILIES as FAMILIES,\n"
        "    TABLE as TABLE,\n"
        "    Client as Client,\n"
        "    client as client,\n" + "".join(f"    {name.capitalize()}Family,\n" for name in names) + ")\n"
        "from ._errors import LayerFSError as LayerFSError\n"
        "from ._values import (\n"
        "    JSON as JSON,\n"
        "    DoctorReport as DoctorReport,\n"
        "    Progress as Progress,\n"
        "    Result as Result,\n"
        "    Scope as Scope,\n"
        ")\n"
        "\n"
        f"def doctor(home: {HOME} = None, *, target: str | None = None, name: str | None = None, timeout: str | None = None, quick: bool | None = None, write_test: bool | None = None) -> DoctorReport:\n"
        '    """Diagnoses without LayerFS state changes; backup write_test uses its own temporary S3 version."""\n'
        "\n"
        "def close() -> int:\n"
        '    """Closes every Store this process holds open with no call running."""\n'
        "\n"
        f"{attributes(entries, '')}\n"
        f"__all__ = {['FAMILIES', 'TABLE', 'Client', 'LayerFSError'] + sorted(names + ['client', 'close', 'doctor'])!r}\n"
    )
    return {"_client.pyi": sync, "aio.pyi": asynchronous, "__init__.pyi": package}


def main(argv):
    stubs = render(table())
    if "--check" in argv:
        stale = [
            name
            for name, text in stubs.items()
            if not (PACKAGE / name).is_file() or (PACKAGE / name).read_text() != text
        ]
        for name in stale:
            print(f"{name}: differs from the call table; run api/python/tools/gen_stubs.py", file=sys.stderr)
        return 1 if stale else 0
    for name, text in stubs.items():
        (PACKAGE / name).write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
