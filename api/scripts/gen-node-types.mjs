// Generates api/node/src/index.d.ts from the call table the package exports.
//   node api/scripts/gen-node-types.mjs          write the file
//   node api/scripts/gen-node-types.mjs --check  exit 1 when the file is not what the table gives
// It needs the built addon (the table comes from it). `render` is also what
// api/node/test/types.mjs compares the committed file with.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";

const output = fileURLToPath(new URL("../node/src/index.d.ts", import.meta.url));

// What a table kind accepts as an argument. `project` is "<store>/<project>".
const ARGUMENT = {
  project: "string",
  name: "string",
  text: "string",
  int: "WholeNumber",
  bool: "boolean",
  size: "Size",
  content: "Content",
  json: "Value",
};
const FUNCTION = { on_progress: "ProgressHandler", stdout: "OutputHandler", stderr: "OutputHandler" };

const pascal = (word) => word.replace(/(^|_)([a-z])/g, (_, __, letter) => letter.toUpperCase());

function argument(spec, arg) {
  const type = ARGUMENT[arg.kind];
  if (!type) throw new Error(`${spec.family}.${spec.call}: no type for argument kind "${arg.kind}"`);
  return `${arg.name}${arg.optional ? "?" : ""}: ${type}${arg.optional ? " | null" : ""}`;
}

function option(spec, opt) {
  const type = opt.kind === "function" ? FUNCTION[opt.name] : ARGUMENT[opt.kind];
  if (!type) throw new Error(`${spec.family}.${spec.call}: no type for option "${opt.name}" of kind "${opt.kind}"`);
  return `  ${opt.name}?: ${type};`;
}

/** The text of index.d.ts for `table`: `[{ family, call, args, options, help }]`. */
export function render(table) {
  const families = [...new Set(table.map((spec) => spec.family))];
  const out = [`// Generated by api/scripts/gen-node-types.mjs from the call table (\`table\`). Do not edit.
// Run \`node api/scripts/gen-node-types.mjs\` after a change to the table.
/// <reference types="node" />

/** Any value the package returns or accepts as JSON: whole numbers beyond
 * ±(2^53 - 1) are \`bigint\`, bytes that are not UTF-8 are \`Buffer\`. */
export type Value = null | boolean | number | bigint | string | Uint8Array | Value[] | { [key: string]: Value };
/** An answer: a map with snake_case keys. The call table has no result schema,
 * so its keys are not typed; the call's page in the SDK reference lists them. */
export type Result = { [key: string]: Value };
/** A whole number: a \`number\` that is a safe integer, or a \`bigint\`. */
export type WholeNumber = number | bigint;
/** A size: a number of bytes, or text such as \`"512M"\` or \`"8G"\`. */
export type Size = WholeNumber | string;
/** File content: text, or bytes. */
export type Content = string | Uint8Array;
/** Receives each progress update of the call. */
export type ProgressHandler = (progress: Value) => void;
/** Receives command output as it is passed on: a string when the bytes are UTF-8, else a Buffer. */
export type OutputHandler = (bytes: string | Buffer) => void;

/** A refused call: \`code\` is stable (InvalidInput, NotFound, InUse, Exists,
 * Conflict, Unsupported, Unavailable, Unknown, Failed, …). */
export class LayerFSError extends Error {
  constructor(code: string, message: string, detail?: Value | null);
  readonly name: "LayerFSError";
  readonly code: string;
  readonly detail: Value | null;
}

/** A folder scope binding a client to one project. */
export interface Scope {
  project: string;
  folder: string;
  branch?: string;
}

export interface ClientOptions {
  /** Default \`LAYERFS_HOME\`, else \`~/.layerfs\`. */
  home?: string;
  scope?: Scope;
}

export interface CallSpec {
  family: string;
  call: string;
  args: readonly { name: string; kind: string; optional: boolean }[];
  options: readonly { name: string; kind: string; optional: boolean }[];
  help: string;
}

export interface DoctorReport {
  ok: boolean;
  findings: { severity: string; entity: { kind: string; name: string }; message: string; fix: string | null }[];
}
`];
  for (const spec of table) {
    if (spec.options.length === 0) continue;
    out.push(`/** Options of \`${spec.family}.${spec.call}\`; an unknown option is refused. */
export interface ${pascal(spec.family)}${pascal(spec.call)}Options {
${spec.options.map((opt) => option(spec, opt)).join("\n")}
}
`);
  }
  for (const family of families) {
    const members = table.filter((spec) => spec.family === family).map((spec) => {
      const params = spec.args.map((arg) => argument(spec, arg));
      const signature = (list) => `  ${spec.call}(${list.join(", ")}): Promise<Result>;`;
      const signatures = [];
      if (spec.options.length > 0) {
        const type = `${pascal(spec.family)}${pascal(spec.call)}Options`;
        params.push(`options?: ${type}`);
        // the binding takes a plain object in a text, name or number slot as the
        // options (index.js, `bind`): so the options may follow the required
        // positionals directly, omitting the optional ones
        const required = spec.args.reduce((last, arg, index) => (arg.optional ? last : index), -1) + 1;
        for (let at = required; at < spec.args.length; at += 1) {
          if (spec.args[at].kind === "json") continue;
          signatures.push(signature([...spec.args.slice(0, at).map((arg) => argument(spec, arg)), `options: ${type}`]));
        }
      }
      signatures.push(signature(params));
      return `  /** ${spec.help} */\n${signatures.join("\n")}`;
    });
    out.push(`export interface ${pascal(family)}Family {\n${members.join("\n")}\n}\n`);
  }
  out.push(`export interface Client {
  readonly home: string | undefined;
  readonly scope: Scope | undefined;
${families.map((family) => `  readonly ${family}: ${pascal(family)}Family;`).join("\n")}
}

/** The call table: one entry per call. */
export const table: readonly CallSpec[];
/** The families, in help order. */
export const families: readonly string[];

/** A client of \`home\` with an optional folder scope. */
export function client(options?: ClientOptions): Client;
/** What is wrong in \`home\`; changes nothing and starts no machine. Outside the call table. */
export function doctor(options?: { home?: string }): Promise<DoctorReport>;
/** Closes every Store this process holds open with no call running; answers how many. Outside the call table. */
export function close(): number;

${families.map((family) => `export const ${family}: ${pascal(family)}Family;`).join("\n")}

declare const layerfs: Client & {
  client: typeof client;
  close: typeof close;
  doctor: typeof doctor;
  table: typeof table;
  families: typeof families;
  LayerFSError: typeof LayerFSError;
};
export default layerfs;
`);
  return out.join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { table } = await import("../node/src/index.js");
  const text = render(table);
  if (process.argv.includes("--check")) {
    if (readFileSync(output, "utf8") !== text) {
      console.error("api/node/src/index.d.ts differs from the call table; run node api/scripts/gen-node-types.mjs");
      process.exit(1);
    }
  } else {
    writeFileSync(output, text);
    console.log(`Wrote ${output}`);
  }
}
